def apply(groups) -> None:
    """Add the nodes to the group «Фабрика» (once)."""
    plant = next(g for g in groups if g["id"] == "plant")
    have = {n["id"] for n in plant["nodes"]}
    plant["nodes"].extend(n for n in NODES if n["id"] not in have)
