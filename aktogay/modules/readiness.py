def by_id(rid: str) -> dict:
    for r in READY:
        if r["id"] == rid:
            return r
    raise KeyError(rid)


def missing() -> list[str]:
    """Empty fields of the nine points (a card is not finished while one is empty)."""
    out = []
    for r in READY:
        for f in FIELDS:
            if not str(r.get(f, "")).strip():
                out.append(f"{r['id']}.{f}")
    return out


def json_text() -> str:
    return json.dumps({"items": list(READY)}, ensure_ascii=False, indent=1) + "\n"


def md_text() -> str:
    head = ("# READINESS: новые беды и прогнозы по девяти пунктам готовности\n\n"
            "Файл пишет `aktogay/modules/readiness.py` (`--write-md`), руками не правится; тест сверяет его с кодом. "
            "Девять пунктов: проблема и источник, сигнал на реальной фабрике и в двойнике, правило и параметры, цена, "
            "кого звать и запасной, что делать, закрытие, проверка (сценарий, тест, строка «Как проверить»), границы. "
            "Метки: [факт], [проект], [вендор], [аналог], [расчёт], [допущение], [оценка на модели]. Где источника на "
            "порядок действий нет, написано «уточнить по регламенту площадки».\n\n")
    tab = ("## Путь внедрения: беда → сигнал на реальной фабрике → откуда данные\n\n"
           "| Беда или прогноз | Сигнал на реальной фабрике | Признак в двойнике (Ditto) | Что подключить | Границы |\n"
           "|---|---|---|---|---|\n")
    for r in READY:
        tab += (f"| {r['title']} ({r['kind']}) | {r['signal_real']} | {r['signal_twin']} | {r['connect']} | "
                f"{r['limits']} |\n")
    out = head + tab + "\n"
    for r in READY:
        out += f"## {r['title']} ({r['kind']}, `{r['id']}`)\n\n"
        for n, (f, label) in enumerate((("problem", "Проблема"), ("source", "Источник"), ("signal_real", "Сигнал на реальной фабрике"),
                                        ("signal_twin", "Сигнал в двойнике"), ("rule", "Правило"), ("params", "Параметры"),
                                        ("price", "Цена"), ("who", "Кого звать"), ("backup", "Запасной"),
                                        ("checklist", "Что делать"), ("closure", "Закрытие"), ("scenario", "Сценарий"),
                                        ("test", "Тест"), ("howto", "Строка «Как проверить»"), ("limits", "Границы"),
                                        ("connect", "Что подключить")), 1):
            out += f"- **{label}.** {r[f]}\n"
        out += "\n"
    return out


def main(argv: list[str] | None = None) -> int:
    a = list(sys.argv[1:] if argv is None else argv)
    bad = missing()
    if bad:
        print("empty:", ", ".join(bad))
        return 1
    done = False
    while a:
        k = a.pop(0)
        path = a.pop(0) if a else ""
        if k == "--write-json" and path:
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(json_text())
            done = True
        elif k == "--write-md" and path:
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(md_text())
            done = True
        else:
            print("usage: readiness.py [--write-json PATH] [--write-md PATH]")
            return 2
    if not done:
        print(f"ok: {len(READY)} cards, nine points each")
    return 0


if __name__ == "__main__":
    sys.exit(main())
